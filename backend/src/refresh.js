// backend/src/refresh.js — the Monday cron (wrangler.toml [triggers]):
// generate hints for LeetCode's newest problems before users open them, so
// the first visitor of a new problem gets a cache hit too.
//
// The cron fires every 10 minutes from 06:00 to 08:50 UTC on Mondays and each
// run generates at most ONE problem (limit: 1). One run doing all ~20 in a row
// (Hard ones take 1-4 min each on Workers AI) can hit the Workers Free plan's
// per-invocation limits; on 2026-11-09 the single 06:00 run wrote nothing.
// Each run starts at a different place in the list, so a problem that keeps
// failing never blocks the others.
//
//   • fetches the newest ~20 problems from LeetCode GraphQL
//   • skips premium ones and ones already in the cache
//   • skips problems of a contest that is running right now (no hints for a
//     live contest); they are generated by next week's run
//   • writes the reply under the SAME key a user's plain C++ request uses
// The weekly sync-cache GitHub Action (.github/workflows) exports these D1 rows as
// cache-site/cache/<slug>.json (tools/export-d1.mjs).

import { PROMPT_VERSION, buildPrompt } from '../../shared/prompts.js';
import { htmlToText } from '../../shared/html-text.js';
import { openStream } from './providers.js';
import { readCache, writeCache, isCompleteReply, cacheableFrom } from './store.js';

const NEWEST = 20;
const SNIPPET_LANGS = ['cpp', 'java', 'python3', 'c', 'javascript', 'typescript', 'csharp', 'golang', 'kotlin', 'swift', 'rust'];

async function leetcode(query, variables = {}) {
  const res = await fetch('https://leetcode.com/graphql', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Referer: 'https://leetcode.com/problemset/', 'User-Agent': 'LeetHint-refresh' },
    body: JSON.stringify({ query, variables }),
    signal: AbortSignal.timeout(10000)
  });
  if (!res.ok) throw new Error(`LeetCode GraphQL HTTP ${res.status}`);
  return (await res.json()).data;
}

export async function newestProblems(n = NEWEST) {
  const list = `query list($limit: Int, $skip: Int) {
    questionList(categorySlug: "", limit: $limit, skip: $skip, filters: {}) { totalNum data { titleSlug isPaidOnly } }
  }`;
  const total = (await leetcode(list, { limit: 1, skip: 0 })).questionList.totalNum;
  const page = (await leetcode(list, { limit: n, skip: Math.max(0, total - n) })).questionList.data;
  return page.filter(q => !q.isPaidOnly).map(q => q.titleSlug);
}

// Slugs of problems in a contest that is running now
// (topTwoContests gives start times; contestQuestionList the problems —
// both checked 2026-11-07 for upcoming/finished contests, and
// contestQuestionList confirmed during a live contest: Weekly Contest 527 on
// 2026-11-08 02:35 UTC returned all 4 problems. An error or an empty list for
// a live contest still skips the whole run, to be safe. The Monday 06:00 UTC
// cron never overlaps LeetCode's Saturday/Sunday contests anyway.)
export async function liveContestSlugs(now = Date.now()) {
  const contests = (await leetcode('{ topTwoContests { titleSlug startTime duration } }')).topTwoContests || [];
  const live = contests.filter(c => c.startTime * 1000 <= now && now < (c.startTime + c.duration) * 1000);
  const slugs = new Set();
  for (const c of live) {
    try {
      const qs = (await leetcode('query q($s: String!) { contestQuestionList(contestSlug: $s) { titleSlug } }', { s: c.titleSlug })).contestQuestionList || [];
      if (!qs.length) throw new Error('no problem list');   // hidden while live → unknown
      for (const q of qs) slugs.add(q.titleSlug);
    } catch (e) {
      console.warn(`refresh: questions of live ${c.titleSlug} unknown (${e.message}) — skipping this run`);
      throw new Error('a contest is live and its problems are unknown');
    }
  }
  return { live: live.map(c => c.titleSlug), slugs };
}

// The problem as the extension would send it (content/content.js)
async function problemData(slug) {
  const q = (await leetcode(`query questionData($titleSlug: String!) {
    question(titleSlug: $titleSlug) { questionFrontendId title difficulty content hints topicTags { name } codeSnippets { langSlug code } }
  }`, { titleSlug: slug })).question;
  if (!q?.content) return null;
  const snippets = Object.fromEntries((q.codeSnippets || []).filter(s => SNIPPET_LANGS.includes(s.langSlug)).map(s => [s.langSlug, s.code]));
  return {
    slug, title: q.title, problemNumber: String(q.questionFrontendId || ''), difficulty: q.difficulty,
    description: htmlToText(q.content), cppSnippet: snippets.cpp || '',
    topicTags: (q.topicTags || []).map(t => t.name), officialHints: (q.hints || []).map(htmlToText)
  };
}

async function sha256(text) {
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map(b => b.toString(16).padStart(2, '0')).join('');
}

// Any current-version hints row for this problem? (one indexed range read —
// no LeetCode call, no prompt building, so cached problems cost almost no CPU)
async function hasHintsRow(env, slug) {
  if (!env.DB) return false;
  const prefix = `${PROMPT_VERSION}:hints:${slug}:`;
  try {
    return !!(await env.DB.prepare('SELECT 1 FROM cache WHERE key >= ? AND key < ? LIMIT 1').bind(prefix, prefix + '\uffff').first());
  } catch { return false; }
}

// Which 10-minute run of the morning this is (06:00 → 0, 06:10 → 1, ...)
export const runIndex = now => Math.max(0, Math.floor((now % 86400000 - 6 * 3600000) / 600000));

// → { generated: [...], cached: [...], skipped: [...] }
// limit: most problems to generate (or try) in this run — the cron passes 1
export async function refreshNewProblems(env, { now = Date.now(), slugs, limit = Infinity } = {}) {
  const out = { generated: [], cached: [], skipped: [] };
  const contest = await liveContestSlugs(now);
  if (contest.live.length) console.log(`refresh: live contest ${contest.live.join(', ')} — its problems wait for next week`);
  let list = slugs || await newestProblems();
  if (Number.isFinite(limit) && list.length) {
    const start = runIndex(now) % list.length;
    list = [...list.slice(start), ...list.slice(0, start)];
  }
  let tried = 0;
  for (const slug of list) {
    if (tried >= limit) break;
    if (contest.slugs.has(slug)) { out.skipped.push(slug); continue; }
    if (await hasHintsRow(env, slug)) { out.cached.push(slug); continue; }
    try {
      const problem = await problemData(slug);
      if (!problem) { out.skipped.push(slug); continue; }
      // Mirrors handleGenerate(): sanitizeProblem() lower-cases the slug and
      // clips long fields, which real problems never reach
      const prompt = buildPrompt('hints', problem);
      const key = `${PROMPT_VERSION}:hints:${slug}:${await sha256(prompt)}`.slice(0, 500);
      if (await readCache(env, key, now)) { out.cached.push(slug); continue; }
      tried++;
      const hard = /hard/i.test(problem.difficulty);
      const { upstream, kind, label } = await openStream(env, prompt, {
        effort: hard ? 'high' : 'medium', maxTokens: hard ? 8000 : 4500, tier: hard ? 'hard' : 'main',
        easy: /easy/i.test(problem.difficulty), share: 'hints'
      });
      const raw = await new Response(upstream.body).text();
      if (!isCompleteReply(raw, kind)) { console.warn(`refresh: ${slug} reply incomplete (${label})`); out.skipped.push(slug); continue; }
      if (!cacheableFrom(key, label)) { console.warn(`refresh: ${slug} answered by a small model (${label}) — not cached`); out.skipped.push(slug); continue; }
      await writeCache(env, key, raw, kind, now);
      console.log(`refresh: ${slug} → ${label}`);
      out.generated.push(slug);
    } catch (e) {
      console.warn(`refresh: ${slug} failed: ${e.message}`);
      out.skipped.push(slug);
      if (e.status === 429) break;   // everything busy — next week
    }
  }
  console.log(`refresh: ${out.generated.length} generated, ${out.cached.length} already cached, ${out.skipped.length} skipped`);
  return out;
}
